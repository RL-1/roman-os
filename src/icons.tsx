export type IconName = keyof typeof MAPS

function build(rows: string[]) {
  const solid: string[] = []
  const dither: string[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < 16) {
      const c = row[x] ?? '.'
      if (c === '#') {
        let end = x
        while (row[end + 1] === '#') end++
        solid.push(`M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`)
        x = end + 1
        continue
      }
      if (c === '+' && (x + y) % 2 === 0) dither.push(`M${x} ${y}h1v1h-1z`)
      x++
    }
  })
  return { solid: solid.join(''), dither: dither.join('') }
}

const PATHS = Object.fromEntries(Object.entries(MAPS).map(([k, v]) => [k, build(v)])) as Record<IconName, ReturnType<typeof build>>

export const PixelIcon = memo(function PixelIcon({ name, className }: { name: IconName; className?: string }) {
  const p = PATHS[name]
  return (
    <svg className={className} viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      <path d={p.dither} fill="currentColor" opacity="0.55" />
      <path d={p.solid} fill="currentColor" />
    </svg>
  )
})
